package context

import (
	"context"
	"fmt"
	"math/rand"
	"time"
)

// ContextKey тип для ключей контекста, используется для типобезопасного хранения значений в контексте
type ContextKey string

const (
	// TraceIDKey ключ для traceId в контексте, используется для извлечения идентификатора трассировки из контекста
	TraceIDKey ContextKey = "traceId"
)

// GenerateTraceID генерирует уникальный идентификатор для трассировки запросов
// Используется для связывания всех логов, связанных с одним запросом
// Генерация основана на текущем времени в наносекундах и случайном числе для обеспечения уникальности
func GenerateTraceID() string {
	// Инициализируем генератор случайных чисел с текущим временем в наносекундах
	rand.Seed(time.Now().UnixNano())
	
	// Генерируем уникальный ID, комбинируя время в наносекундах и случайное число
	// Это обеспечивает высокую вероятность уникальности ID даже при множественных запросах в одно и то же время
	return fmt.Sprintf("%d%d", time.Now().UnixNano(), rand.Intn(1000000))
}

// WithTraceID добавляет traceId в контекст для последующего извлечения
// Позволяет передавать идентификатор трассировки через контекст между различными функциями и сервисами
// ctx - исходный контекст, в который будет добавлен traceId
// traceID - идентификатор трассировки, который будет добавлен в контекст
// Возвращает новый контекст с добавленным traceId
func WithTraceID(ctx context.Context, traceID string) context.Context {
	// Создаем новый контекст с добавленным значением traceId
	// Используем типобезопасный ключ TraceIDKey для хранения значения
	return context.WithValue(ctx, TraceIDKey, traceID)
}

// GetTraceID извлекает traceId из контекста
// Используется для получения идентификатора трассировки в различных частях приложения
// ctx - контекст, из которого извлекается traceId
// Возвращает строку с traceId или пустую строку, если traceId не найден в контексте
func GetTraceID(ctx context.Context) string {
	// Пытаемся извлечь traceId из контекста по ключу TraceIDKey
	// Используем type assertion для преобразования interface{} в string
	if traceID, ok := ctx.Value(TraceIDKey).(string); ok {
		// Если traceId найден и успешно преобразован в строку, возвращаем его
		return traceID
	}
	
	// Если traceId не найден в контексте или не может быть преобразован в строку, возвращаем пустую строку
	return ""
}